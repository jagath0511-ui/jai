@dataclass
class BrowserGymEpisodeStep:
    """Represents a single step in a BrowserGym trajectory."""
    step_idx: int
    goal: str
    url: str
    action_raw: str
    action_type: str
    arguments: Dict[str, Any]
    thought: str
    gateway_decision: str
    gateway_risk: str
    reward: float
